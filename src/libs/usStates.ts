// The states matching what's typed: the code first ("fl"), then names that start
// with it ("flo"), then names containing it ("caro")
export function searchUsStates(text: string) {
  const query = text.trim().toLowerCase();
  if (!query) return [...US_STATES];

  const byCode = US_STATES.filter((state) => state.code.toLowerCase() === query);
  const starts = US_STATES.filter(
    (state) => !byCode.includes(state) && state.name.toLowerCase().startsWith(query),
  );
  const contains = US_STATES.filter(
    (state) =>
      !byCode.includes(state) && !starts.includes(state) && state.name.toLowerCase().includes(query),
  );
  return [...byCode, ...starts, ...contains];
}

// "Florida" → "FL"; anything that isn't a US state's name is kept as it is
export function toStateCode(name: string) {
  const match = US_STATES.find((state) => state.name.toLowerCase() === name.trim().toLowerCase());
  return match?.code ?? name;
}
